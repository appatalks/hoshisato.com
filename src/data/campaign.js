export function archiveAlcove(level) {
  const [left, top] = level.secret;
  return { platform: [left + 40, top - 45, 140], artifact: [left + 110, top - 85] };
}

export function starPosition(level, index) {
  if (index >= 3) return routeStars(level)[index - 3];
  let [left, top] = level.crystals[index];
  for (const [relayX, relayY] of level.relays) {
    if (Math.abs(left - relayX) < 70 && Math.abs(top - relayY) < 60) left = relayX - 85;
  }
  return [left, top];
}

export function availableTools(save, level = 0) {
  return TOOLS.filter(
    (tool) =>
      tool.unlock <= Math.max(save.unlocked, level) ||
      (tool.id === 'echo' && save.secrets.length >= 3),
  );
}

export function completion(save) {
  return Math.round(
    ((save.completed.length + save.secrets.length + save.lore.length + save.crystals.length / 5) /
      40) *
      100,
  );
}
